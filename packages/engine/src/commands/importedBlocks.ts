import type { Block, Heading, Mark, NexusDocument, Paragraph, ResourceRef, TextRun } from "../model/types";
import { getPlainText, isParagraphLike } from "../model/tree";
import { engineError } from "../errors/errors";
import { err, ok } from "../utils/result";
import type { Command } from "./types";

function splitRuns(runs: TextRun[], offset: number, generateId: () => string): { before: TextRun[]; after: TextRun[] } {
  const before: TextRun[] = [];
  const after: TextRun[] = [];
  let consumed = 0;
  for (const run of runs) {
    const runStart = consumed;
    const runEnd = consumed + run.text.length;
    if (runEnd <= offset) before.push(run);
    else if (runStart >= offset) after.push(run);
    else {
      const cut = offset - runStart;
      before.push({ ...run, text: run.text.slice(0, cut) });
      after.push({ ...run, id: generateId(), text: run.text.slice(cut) });
    }
    consumed = runEnd;
  }
  return { before, after };
}

function cloneRuns(runs: TextRun[], generateId: () => string): TextRun[] {
  return runs.map(run => ({ ...run, id: generateId(), marks: run.marks.map(mark => ({ ...mark } as Mark)) }));
}

function cloneParagraph(block: Paragraph, generateId: () => string): Paragraph {
  return { ...block, id: generateId(), children: cloneRuns(block.children, generateId) };
}

function cloneBlock(block: Block, generateId: () => string, resourceIds: Map<string, string>): Block {
  switch (block.type) {
    case "paragraph":
      return cloneParagraph(block, generateId);
    case "heading":
      return { ...block, id: generateId(), children: cloneRuns(block.children, generateId) } as Heading;
    case "blockquote":
      return { ...block, id: generateId(), children: block.children.map(child => cloneParagraph(child, generateId)) };
    case "thematicBreak":
      return { ...block, id: generateId() };
    case "bulletList":
    case "orderedList":
      return { ...block, id: generateId(), children: block.children.map(item => ({
        ...item,
        id: generateId(),
        children: item.children.map(child => child.type === "paragraph" ? cloneParagraph(child, generateId) : cloneBlock(child, generateId, resourceIds) as typeof child),
      })) };
    case "table":
      return { ...block, id: generateId(), children: block.children.map(row => ({
        ...row,
        id: generateId(),
        children: row.children.map(cell => ({
          ...cell,
          id: generateId(),
          children: cell.children.map(child => cloneBlock(child, generateId, resourceIds)),
          images: cell.images?.map(image => {
            const resourceId = resourceIds.get(image.resourceId);
            if (!resourceId) throw engineError("INVALID_DOCUMENT", `Imported cell image references missing resource "${image.resourceId}"`);
            return { ...image, id: generateId(), resourceId };
          }),
        })),
      })) };
    case "image": {
      const resourceId = resourceIds.get(block.resourceId);
      if (!resourceId) throw engineError("INVALID_DOCUMENT", `Imported image references missing resource "${block.resourceId}"`);
      return { ...block, id: generateId(), resourceId };
    }
  }
}

function topLevelIndex(content: Block[], id: string): number {
  return content.findIndex(block => block.id === id);
}

function ensureRuns(runs: TextRun[], generateId: () => string): TextRun[] {
  return runs.length ? runs : [{ type: "text", id: generateId(), text: "", marks: [] }];
}

/**
 * Inserts sanitized/imported blocks at a selection inside a top-level paragraph or heading.
 * All inserted node IDs and resource IDs are regenerated by the engine, preventing collisions.
 */
export function insertImportedBlocksAtSelection(params: {
  blockId: string;
  start: number;
  end: number;
  blocks: Block[];
  resources?: ResourceRef[];
}): Command {
  return (doc, ctx) => {
    const index = topLevelIndex(doc.content, params.blockId);
    if (index < 0) return err(engineError("NODE_NOT_FOUND", `Top-level text block "${params.blockId}" not found`, { path: params.blockId }));
    const source = doc.content[index]!;
    if (!isParagraphLike(source)) return err(engineError("UNSUPPORTED_OPERATION", "Imported content can only be inserted into a top-level paragraph or heading", { path: params.blockId }));
    const length = getPlainText(source).length;
    if (params.start < 0 || params.end < params.start || params.end > length) return err(engineError("INVALID_POSITION", "Imported content selection is outside the text block", { path: params.blockId }));
    if (!params.blocks.length) return err(engineError("INVALID_DOCUMENT", "No imported blocks were provided"));
    const firstSplit = splitRuns(source.children, params.start, ctx.generateId);
    const secondSplit = splitRuns(firstSplit.after, params.end - params.start, ctx.generateId);
    const prefix = firstSplit.before;
    const suffix = secondSplit.after;
    const importedResources = params.resources ?? [];
    const resourceIds = new Map<string, string>();
    const resources = importedResources.map(resource => {
      const id = ctx.generateId();
      resourceIds.set(resource.id, id);
      return { ...resource, id };
    });
    let inserted: Block[];
    try {
      inserted = params.blocks.map(block => cloneBlock(block, ctx.generateId, resourceIds));
    } catch (error) {
      return err(error instanceof Error ? engineError("INVALID_DOCUMENT", error.message, { path: params.blockId }) : error as ReturnType<typeof engineError>);
    }
    const content = [...doc.content];
    let selection: { blockId: string; offset: number };
    if (inserted.length === 1 && isParagraphLike(inserted[0]!)) {
      const incoming = inserted[0]!;
      const children = [...prefix, ...incoming.children, ...suffix];
      const merged = { ...source, children: ensureRuns(children, ctx.generateId) } as typeof source;
      content[index] = merged;
      selection = { blockId: source.id, offset: params.start + getPlainText(incoming).length };
    } else {
      let remaining = inserted;
      if (prefix.length === 0 && isParagraphLike(remaining[0]!)) {
        const first = remaining[0]!;
        content[index] = { ...first, id: source.id } as Block;
        remaining = remaining.slice(1);
      } else {
        content[index] = { ...source, children: ensureRuns(prefix, ctx.generateId) } as typeof source;
      }
      if (remaining.length) {
        const last = remaining[remaining.length - 1]!;
        if (isParagraphLike(last)) {
          const caretOffset = getPlainText(last).length;
          remaining[remaining.length - 1] = { ...last, children: ensureRuns([...last.children, ...suffix], ctx.generateId) } as Block;
          selection = { blockId: last.id, offset: caretOffset };
        } else if (suffix.length) {
          const trailing: Paragraph = { type: "paragraph", id: ctx.generateId(), children: ensureRuns(suffix, ctx.generateId) };
          remaining = [...remaining, trailing];
          selection = { blockId: trailing.id, offset: 0 };
        } else {
          selection = { blockId: source.id, offset: getPlainText(source).length };
        }
        content.splice(index + 1, 0, ...remaining);
      } else {
        if (suffix.length) {
          const trailing: Paragraph = { type: "paragraph", id: ctx.generateId(), children: ensureRuns(suffix, ctx.generateId) };
          content.splice(index + 1, 0, trailing);
          selection = { blockId: trailing.id, offset: 0 };
        } else {
          selection = { blockId: content[index]!.id, offset: getPlainText(content[index] as Paragraph).length };
        }
      }
    }
    return ok({ document: { ...doc, content, resources: [...doc.resources, ...resources] }, selection });
  };
}


function plainLength(block: Paragraph): number {
  return block.children.reduce((total, run) => total + run.text.length, 0);
}

/**
 * Inserts rich paragraph content into a paragraph nested inside a quote, list item,
 * or table cell. The parent container's schema is preserved; unsupported structural
 * blocks are rejected instead of silently flattening them.
 */
export function insertImportedBlocksAtNestedSelection(params: {
  blockId: string;
  start: number;
  end: number;
  blocks: Block[];
}): Command {
  return (doc, ctx) => {
    const incoming = params.blocks;
    if (!incoming.length || incoming.some(block => block.type !== "paragraph" && block.type !== "heading")) {
      return err(engineError("UNSUPPORTED_OPERATION", "Nested rich paste currently accepts paragraph and heading blocks only"));
    }
    let found = false;
    let selection: { blockId: string; offset: number } | undefined;
    const makeParagraph = (block: Paragraph | Heading, id: string): Paragraph => ({
      type: "paragraph",
      id,
      ...(block.align ? { align: block.align } : {}),
      ...(block.indent !== undefined ? { indent: block.indent } : {}),
      ...(block.spacingBefore !== undefined ? { spacingBefore: block.spacingBefore } : {}),
      ...(block.spacingAfter !== undefined ? { spacingAfter: block.spacingAfter } : {}),
      ...(block.lineSpacing !== undefined ? { lineSpacing: block.lineSpacing } : {}),
      children: block.children.map(run => ({ ...run, id: ctx.generateId(), marks: run.marks.map(mark => ({ ...mark } as Mark)) })),
    });
    const insertAtParagraphs = (paragraphs: Paragraph[]): Paragraph[] => {
      const index = paragraphs.findIndex(paragraph => paragraph.id === params.blockId);
      if (index < 0) return paragraphs;
      if (found) return paragraphs;
      found = true;
      const source = paragraphs[index]!;
      const length = plainLength(source);
      if (params.start < 0 || params.end < params.start || params.end > length) throw engineError("INVALID_POSITION", "Nested rich paste selection is outside the text block", { path: params.blockId });
      const left = splitRuns(source.children, params.start, ctx.generateId);
      const right = splitRuns(left.after, params.end - params.start, ctx.generateId);
      const prefix = left.before;
      const suffix = right.after;
      const cloned = incoming.map(block => makeParagraph(block as Paragraph | Heading, ctx.generateId()));
      const replacement: Paragraph[] = [];
      if (prefix.some(run => run.text.length)) replacement.push({ ...source, children: prefix });
      if (cloned.length) replacement.push(...cloned);
      if (suffix.some(run => run.text.length)) {
        const last = replacement[replacement.length - 1];
        if (last) replacement[replacement.length - 1] = { ...last, children: [...last.children, ...suffix] };
        else replacement.push({ ...source, children: suffix });
      }
      if (!replacement.length) replacement.push({ ...source, children: [{ type: "text", id: ctx.generateId(), text: "", marks: [] }] });
      if (!prefix.some(run => run.text.length) && replacement[0]) replacement[0] = { ...replacement[0], id: source.id };
      paragraphs.splice(index, 1, ...replacement);
      const last = replacement[replacement.length - 1]!;
      selection = { blockId: last.id, offset: plainLength(last) - suffix.reduce((total, run) => total + run.text.length, 0) };
      return paragraphs;
    };
    const visit = (block: Block): Block => {
      if (block.type === "blockquote") return { ...block, children: insertAtParagraphs([...block.children]) };
      if (block.type === "bulletList" || block.type === "orderedList") {
        return { ...block, children: block.children.map(item => ({ ...item, children: item.children.map(child => {
          if (child.type === "paragraph") {
            const next = insertAtParagraphs([child]);
            return next;
          }
          return visit(child) as typeof child;
        }).flat() })) } as Block;
      }
      if (block.type === "table") return { ...block, children: block.children.map(row => ({ ...row, children: row.children.map(cell => ({ ...cell, children: cell.children.flatMap(child => child.type === "paragraph" ? insertAtParagraphs([child]) : [visit(child)]) })) })) };
      return block;
    };
    let content: Block[];
    try {
      content = doc.content.map(block => {
        if (block.type === "paragraph" || block.type === "heading") return block;
        return visit(block);
      });
    } catch (error) {
      return err(error instanceof Error && "code" in error ? error as ReturnType<typeof engineError> : engineError("INVALID_POSITION", error instanceof Error ? error.message : "Nested paste failed"));
    }
    if (!found) return err(engineError("NODE_NOT_FOUND", `Nested text block "${params.blockId}" was not found`, { path: params.blockId }));
    return ok({ document: { ...doc, content }, ...(selection ? { selection } : {}) });
  };
}
